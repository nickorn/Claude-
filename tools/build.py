#!/usr/bin/env python3
"""Build helper for Patent-Tools (Python 3 standard library only, offline).

Steps:
  1. Generate src/modules/modDefaults.bas from config/settings.json and
     config/blacklist.json (embedded defaults for the first run).
  2. Check the VBA sources in src/, tests/vba/ and tools/ (ASCII only, CRLF,
     Option Explicit, VB_Name = file name, declarations, blocks) and run
     tools/vba_lint.py (undeclared names, ByRef types, reserved names, ...).
     The ribbon XML is checked against the customUI attributes and callbacks.
  3. Assemble build/PatentTools.dotm: an empty macro-enabled template with the
     ribbon from src/customUI. The VBA modules are imported afterwards in Word
     (see README) because vbaProject.bin can only be written by Office.

Usage:
  python3 tools/build.py                    build a fresh template shell
  python3 tools/build.py --update FILE      replace only the ribbon in an existing
                                            .dotm, keeping its imported VBA code
"""
import argparse
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
CONFIG = ROOT / "config"
OUT = ROOT / "build" / "PatentTools.dotm"

UI_REL_TYPE = "http://schemas.microsoft.com/office/2007/relationships/ui/extensibility"
UI_PART = "customUI/customUI14.xml"

CONTENT_TYPES = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Default Extension="png" ContentType="image/png"/>
<Override PartName="/word/document.xml" ContentType="application/vnd.ms-word.template.macroEnabledTemplate.main+xml"/>
</Types>
"""

ROOT_RELS = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
<Relationship Id="rIdPatentToolsUI" Type="{UI_REL_TYPE}" Target="{UI_PART}"/>
</Relationships>
"""

DOCUMENT = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
<w:body>
<w:p><w:r><w:t>Patent-Tools – globale Vorlage. Dieses Dokument bleibt leer; die Funktionen stehen im Menüband „Patent-Tools“.</w:t></w:r></w:p>
<w:sectPr/>
</w:body>
</w:document>
"""


# ---------------------------------------------------------------- modDefaults

def ascii_json(text: str, source: Path) -> str:
    """Escape non-ASCII characters as \\uXXXX so the .bas file stays ASCII.
    modJson.DecodeJsonUnicode turns them back when the files are written."""
    if "\\u" in text:
        sys.exit(f"{source}: literal \\u sequences are not supported in default files")
    return "".join(c if ord(c) < 128 else f"\\u{ord(c):04x}" for c in text)


def vba_string_function(name: str, text: str) -> str:
    lines = [f"Public Function {name}() As String", "    Dim s As String"]
    for line in text.rstrip("\n").split("\n"):
        lines.append(f'    s = s & "{line.replace(chr(34), chr(34) * 2)}" & vbLf')
    lines += [f"    {name} = s", "End Function"]
    return "\n".join(lines)


def generate_defaults() -> Path:
    settings = CONFIG / "settings.json"
    blacklist = CONFIG / "blacklist.json"
    body = [
        'Attribute VB_Name = "modDefaults"',
        "Option Explicit",
        "",
        "' GENERATED by tools/build.py from config/settings.json and config/blacklist.json.",
        "' Do not edit by hand - change the files in config/ and run the build again.",
        "' Non-ASCII characters are stored as \\uXXXX (see modJson.DecodeJsonUnicode).",
        "",
        vba_string_function("DefaultSettingsJson", ascii_json(settings.read_text(encoding="utf-8"), settings)),
        "",
        vba_string_function("DefaultBlacklistJson", ascii_json(blacklist.read_text(encoding="utf-8"), blacklist)),
        "",
    ]
    target = SRC / "modules" / "modDefaults.bas"
    target.write_text("\n".join(body), encoding="ascii", newline="\r\n")
    return target


# ---------------------------------------------------------------- checks

def check_sources() -> list[str]:
    problems = []
    paths = [*SRC.rglob("*"), *(ROOT / "tests" / "vba").glob("*.bas"), *(ROOT / "tools").glob("*.bas")]
    for path in sorted(paths):
        if path.suffix.lower() not in (".bas", ".cls", ".frm"):
            continue
        raw = path.read_bytes()
        try:
            text = raw.decode("ascii")
        except UnicodeDecodeError:
            problems.append(f"{path.relative_to(ROOT)}: non-ASCII characters (use modStrings tokens / ChrW)")
            continue
        if re.search(r"(?<!\r)\n", text):
            # normalise instead of failing: editors on Linux/macOS write LF
            text = text.replace("\r\n", "\n").replace("\n", "\r\n")
            path.write_bytes(text.encode("ascii"))
            print("normalised line endings to CRLF:", path.relative_to(ROOT))
        m = re.search(r'^Attribute VB_Name = "([^"]+)"', text, re.M)
        if not m or m.group(1) != path.stem:
            problems.append(f"{path.relative_to(ROOT)}: VB_Name must equal the file name")
        if not re.search(r"^Option Explicit\s*$", text, re.M):
            problems.append(f"{path.relative_to(ROOT)}: missing Option Explicit")
        problems += declaration_order_problems(path, text)
        problems += block_balance_problems(path, text)
    return problems


PROC_START = re.compile(r"^(?:(?:Public|Private|Friend)\s+)?(?:Static\s+)?(?:Sub|Function|Property\s+(?:Get|Let|Set))\s+\w+", re.I)
MODULE_DECL = re.compile(r"^(?:Public|Private|Global|Dim|Const)\s+(?!Sub\b|Function\b|Property\b|Declare\b)\w+", re.I)


def code_lines(text: str):
    """(line number, code without comment/strings) for every logical line start."""
    for no, line in enumerate(text.split("\r\n"), 1):
        code = re.sub(r'"[^"]*"', '""', line)
        code = code.split("'", 1)[0].rstrip()
        yield no, code


def declaration_order_problems(path: Path, text: str) -> list[str]:
    """VBA requires module-level declarations before the first procedure."""
    seen_proc = False
    for no, code in code_lines(text):
        if PROC_START.match(code):
            seen_proc = True
        elif seen_proc and MODULE_DECL.match(code):
            return [f"{path.relative_to(ROOT)}:{no}: module-level declaration after the first procedure"]
    return []


def block_balance_problems(path: Path, text: str) -> list[str]:
    """Cheap structural check: Sub/Function/Property blocks open and close in order."""
    problems, stack = [], []
    for no, code in code_lines(text):
        if PROC_START.match(code):
            if stack:
                problems.append(f"{path.relative_to(ROOT)}:{no}: procedure starts inside {stack[-1][0]} (line {stack[-1][1]})")
            kind = re.search(r"\b(Sub|Function|Property)\b", code, re.I).group(1).lower()
            stack.append((kind, no))
        m = re.match(r"^End\s+(Sub|Function|Property)\b", code.strip(), re.I)
        if m:
            if not stack or stack[-1][0] != m.group(1).lower():
                problems.append(f"{path.relative_to(ROOT)}:{no}: unexpected End {m.group(1)}")
            else:
                stack.pop()
    if stack:
        problems.append(f"{path.relative_to(ROOT)}: {stack[-1][0]} from line {stack[-1][1]} is not closed")
    return problems


# ---------------------------------------------------------------- settings

# keys read directly (not via GetSettingValue) or informational
SETTINGS_EXTRA = {"version", "description.introPhrases.en", "description.introPhrases.de"}


def settings_problems() -> list[str]:
    """Every key the code reads exists in config/settings.json, and every key
    there is read by the code (otherwise editing it would silently do nothing)."""
    import json
    cfg = json.loads((CONFIG / "settings.json").read_text(encoding="utf-8"))

    def leaves(d, prefix=""):
        for k, v in d.items():
            if isinstance(v, dict):
                yield from leaves(v, prefix + k + ".")
            else:
                yield prefix + k

    defined = set(leaves(cfg))
    used = set()
    code = "\n".join(p.read_text(encoding="ascii") for p in (SRC / "modules").glob("*.bas"))
    used |= set(re.findall(r'GetSettingValue\("([^"]+)"\s*,', code))
    check_keys = re.search(r'CHECK_KEYS As String = "([^"]+)"', code).group(1).split("|")
    used |= {f"check.enabled.{k}" for k in check_keys} | {f"check.highlightColors.{k}" for k in check_keys}
    used |= {f"footer.status.{lang}.{k}" for lang in ("de", "en") for k in ("markedUp", "clean", "inventorApproved")}
    used |= SETTINGS_EXTRA
    problems = [f"config/settings.json: code reads '{k}' but it is not defined" for k in sorted(used - defined)]
    problems += [f"config/settings.json: '{k}' is never read by the code" for k in sorted(defined - used)]
    return problems


# ---------------------------------------------------------------- package

# customUI 2009/07: attributes this project may use per element. Word drops the
# WHOLE ribbon tab without any message if one attribute or element is invalid.
COMMON = {"id", "label", "tag", "screentip", "supertip", "imageMso", "image", "visible", "enabled",
          "getLabel", "getEnabled", "getVisible", "keytip", "showLabel", "showImage"}
UI_ATTRS = {
    "customUI": {"xmlns", "onLoad", "loadImage"},
    "ribbon": {"startFromScratch"},
    "tabs": set(),
    "tab": {"id", "label", "visible", "keytip", "insertAfterMso", "insertBeforeMso", "getLabel"},
    "group": {"id", "label", "visible", "keytip", "imageMso", "image", "screentip", "supertip"},
    "button": COMMON | {"size", "onAction", "description"},
    "menu": COMMON | {"size", "itemSize", "description"},
    "dynamicMenu": COMMON | {"size", "getContent", "invalidateContentOnDrop", "description"},
    "menuSeparator": {"id", "title"},
    "separator": {"id", "visible"},
}
LIMITS = {"label": 1024, "screentip": 1024, "supertip": 1024, "tag": 1024}


def ribbon_problems(data: bytes) -> list[str]:
    import xml.dom.minidom
    dom = xml.dom.minidom.parseString(data)
    problems, ids = [], set()
    for el in dom.getElementsByTagName("*"):
        name = el.tagName
        if name not in UI_ATTRS:
            problems.append(f"customUI14.xml: element <{name}> not allowed here")
            continue
        for attr in el.attributes.keys():
            if attr not in UI_ATTRS[name]:
                problems.append(f"customUI14.xml: <{name}> has no attribute '{attr}'")
            if attr in LIMITS and len(el.getAttribute(attr)) > LIMITS[attr]:
                problems.append(f"customUI14.xml: {attr} of {el.getAttribute('id')} longer than {LIMITS[attr]}")
        if el.hasAttribute("id"):
            i = el.getAttribute("id")
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", i) or i in ids:
                problems.append(f"customUI14.xml: id '{i}' invalid or duplicate")
            ids.add(i)
        if name in ("button", "menu", "dynamicMenu") and el.parentNode.tagName == "group" and not el.hasAttribute("label"):
            problems.append(f"customUI14.xml: {el.getAttribute('id')} has no label")
    callbacks = {el.getAttribute(a) for el in dom.getElementsByTagName("*")
                 for a in ("onAction", "getContent", "onLoad") if el.hasAttribute(a)}
    ribbon_module = (SRC / "modules" / "modRibbon.bas").read_text(encoding="ascii")
    for cb in sorted(callbacks):
        if not re.search(rf"^Public Sub {cb}\(", ribbon_module, re.M):
            problems.append(f"customUI14.xml: callback {cb} not found as Public Sub in modRibbon.bas")
    return problems


def custom_ui() -> bytes:
    data = (SRC / "customUI" / "customUI14.xml").read_bytes()
    problems = ribbon_problems(data)
    if problems:
        sys.exit("\n".join(problems))
    return data


def build_new(out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", CONTENT_TYPES)
        z.writestr("_rels/.rels", ROOT_RELS)
        z.writestr("word/document.xml", DOCUMENT)
        z.writestr(UI_PART, custom_ui())


def update_existing(path: Path) -> None:
    """Swap the ribbon XML inside an existing .dotm and keep everything else."""
    tmp = path.with_suffix(".tmp")
    with zipfile.ZipFile(path) as src, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as dst:
        for item in src.infolist():
            if item.filename == UI_PART:
                continue
            data = src.read(item.filename)
            if item.filename == "_rels/.rels" and UI_PART.encode() not in data:
                data = data.replace(
                    b"</Relationships>",
                    f'<Relationship Id="rIdPatentToolsUI" Type="{UI_REL_TYPE}" Target="{UI_PART}"/></Relationships>'.encode(),
                )
            dst.writestr(item, data)
        dst.writestr(UI_PART, custom_ui())
    tmp.replace(path)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--update", type=Path, help="existing .dotm whose ribbon should be replaced")
    args = ap.parse_args()

    print("generated", generate_defaults().relative_to(ROOT))
    problems = check_sources() + settings_problems()
    import subprocess
    lint = subprocess.run([sys.executable, str(ROOT / "tools" / "vba_lint.py")], capture_output=True, text=True)
    print(lint.stdout.strip().splitlines()[-1])
    if lint.returncode != 0:
        problems.append(lint.stdout.strip())
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    if args.update:
        update_existing(args.update)
        print("updated ribbon in", args.update)
    else:
        build_new(OUT)
        print("built", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
